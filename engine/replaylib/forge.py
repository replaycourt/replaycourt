"""Isolated Foundry workspace per report: set up, compile, run the PoC.

Safety rules for untrusted PoC code:
- our own foundry.toml (ffi = false, fs_permissions = []), never the submitter's,
- empty environment (env -i): only PATH, an own HOME (sandbox directory), FOUNDRY_FFI=false,
- hard time limit; the whole process group is killed when it is exceeded.
"""

import json
import os
import shutil
import signal
import subprocess
import time
from typing import Dict, List, Optional, Tuple

SUPPORT_FILES = ["interface.sol", "basetest.sol", "tokenhelper.sol"]


def write_foundry_toml(ws: str, rpc_endpoints: Dict[str, str], evm_version: str):
    lines = [
        "# Generated by the ReplayCourt engine. The submitter's foundry.toml is never used.",
        "[profile.default]",
        'src = "src"',
        'test = "test"',
        'out = "out"',
        'libs = ["lib"]',
        'remappings = ["forge-std/=lib/forge-std/src/"]',
        "ffi = false",
        "fs_permissions = []",
        'evm_version = "%s"' % evm_version,
        "optimizer = true",
        "optimizer_runs = 200",
        "fork_retries = 6",
        "fork_retry_backoff = 1500",
        "",
        "[rpc_endpoints]",
    ]
    for alias, url in sorted(rpc_endpoints.items()):
        lines.append('%s = "%s"' % (alias, url.replace('"', "")))
    with open(os.path.join(ws, "foundry.toml"), "w") as fh:
        fh.write("\n".join(lines) + "\n")


def build_workspace(ws: str, poc_source: str, forge_std_src: str, support_dir: str,
                    rpc_endpoints: Dict[str, str], evm_version: str) -> str:
    if os.path.exists(ws):
        shutil.rmtree(ws)
    os.makedirs(os.path.join(ws, "test", "poc"))
    os.makedirs(os.path.join(ws, "src"))
    os.makedirs(os.path.join(ws, "lib", "forge-std"))
    shutil.copytree(forge_std_src, os.path.join(ws, "lib", "forge-std", "src"))
    for name in SUPPORT_FILES:
        p = os.path.join(support_dir, name)
        if os.path.isfile(p):
            shutil.copy2(p, os.path.join(ws, "test", name))
    poc_path = os.path.join(ws, "test", "poc", "PoC.t.sol")
    with open(poc_path, "w", encoding="utf-8") as fh:
        fh.write(poc_source)
    write_foundry_toml(ws, rpc_endpoints, evm_version)
    return poc_path


def sandbox_env(home: str) -> Dict[str, str]:
    os.makedirs(home, exist_ok=True)
    return {
        "PATH": "/usr/bin:/bin:/usr/sbin:/sbin",
        "HOME": home,
        "FOUNDRY_FFI": "false",
        "NO_COLOR": "1",
        "TERM": "dumb",
        "LANG": "C",
    }


def run(cmd: List[str], cwd: str, env: Dict[str, str], timeout: int) -> Dict:
    start = time.time()
    proc = subprocess.Popen(cmd, cwd=cwd, env=env, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                            start_new_session=True)
    timed_out = False
    try:
        out, err = proc.communicate(timeout=timeout)
    except subprocess.TimeoutExpired:
        timed_out = True
        try:
            os.killpg(proc.pid, signal.SIGKILL)
        except OSError:
            pass
        out, err = proc.communicate()
    return {
        "cmd": cmd,
        "rc": proc.returncode,
        "stdout": out.decode("utf-8", "replace"),
        "stderr": err.decode("utf-8", "replace"),
        "duration_s": round(time.time() - start, 2),
        "timed_out": timed_out,
    }


def forge_version(forge: str, env: Dict[str, str]) -> str:
    try:
        res = run([forge, "--version"], cwd="/", env=env, timeout=30)
        return res["stdout"].splitlines()[0].strip() if res["stdout"] else "unknown"
    except OSError:
        return "not found"


def forge_build(forge: str, ws: str, env: Dict[str, str], timeout: int) -> Dict:
    return run([forge, "build", "--root", ws], cwd=ws, env=env, timeout=timeout)


def forge_test(forge: str, ws: str, env: Dict[str, str], timeout: int, match_test: Optional[str],
               fork_url: Optional[str], fork_block: Optional[int]) -> Dict:
    cmd = [forge, "test", "--root", ws, "--match-path", "test/poc/PoC.t.sol", "--json", "-vvvv"]
    if match_test:
        cmd += ["--match-test", match_test]
    if fork_url:
        cmd += ["--fork-url", fork_url]
        if fork_block is not None:
            cmd += ["--fork-block-number", str(fork_block)]
    res = run(cmd, cwd=ws, env=env, timeout=timeout)
    res["json"] = None
    text = res["stdout"].strip()
    if text:
        # forge may print lines before the JSON; the JSON object starts with '{'.
        start = text.find("{")
        if start >= 0:
            try:
                res["json"] = json.loads(text[start:])
            except ValueError:
                res["json"] = None
    return res


def load_selectors(ws: str) -> Dict[str, str]:
    """selector (0x........) -> function signature, from all artifacts of the workspace."""
    sel = {}
    out_dir = os.path.join(ws, "out")
    for root, _dirs, files in os.walk(out_dir):
        if "build-info" in root:
            continue
        for name in files:
            if not name.endswith(".json"):
                continue
            try:
                with open(os.path.join(root, name)) as fh:
                    art = json.load(fh)
            except (OSError, ValueError):
                continue
            for sig, s in (art.get("methodIdentifiers") or {}).items():
                sel.setdefault("0x" + s.lower(), sig)
    return sel


def solc_versions(ws: str) -> List[str]:
    """Compiler version(s) from the metadata of the PoC artifacts."""
    vers = set()
    d = os.path.join(ws, "out", "PoC.t.sol")
    if os.path.isdir(d):
        for name in os.listdir(d):
            if not name.endswith(".json"):
                continue
            try:
                with open(os.path.join(d, name)) as fh:
                    meta = json.load(fh).get("metadata") or {}
                if isinstance(meta, str):
                    meta = json.loads(meta)
                v = (meta.get("compiler") or {}).get("version")
                if v:
                    vers.add(v)
            except (OSError, ValueError, AttributeError):
                pass
    return sorted(vers)


def compile_errors(stderr: str, stdout: str, limit: int = 12) -> List[str]:
    text = (stderr or "") + "\n" + (stdout or "")
    lines = [ln.rstrip() for ln in text.splitlines() if ln.strip()]
    keep = [ln for ln in lines if ("Error" in ln or "error" in ln or "-->" in ln)]
    return (keep or lines)[:limit]


def extract_tests(res_json: Optional[Dict]) -> List[Tuple[str, str, Dict]]:
    """[(suite, testname, result), ...]"""
    out = []
    if not isinstance(res_json, dict):
        return out
    for suite, data in res_json.items():
        if not isinstance(data, dict):
            continue
        for tname, tres in (data.get("test_results") or {}).items():
            out.append((suite, tname, tres))
    return out
